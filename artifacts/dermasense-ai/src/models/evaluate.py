from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import seaborn as sns
from sklearn.metrics import (
    accuracy_score,
    balanced_accuracy_score,
    classification_report,
    confusion_matrix,
    f1_score,
    precision_recall_fscore_support,
    roc_auc_score,
)

from src.data.dataset import CLASS_NAMES
from src.models.calibrate import expected_calibration_error


def build_metrics(labels: np.ndarray, probabilities: np.ndarray, threshold: float = 0.70) -> dict:
    predictions = probabilities.argmax(axis=1)
    confidence = probabilities.max(axis=1)
    accepted = confidence >= threshold
    precision, recall, f1, support = precision_recall_fscore_support(
        labels,
        predictions,
        labels=list(range(len(CLASS_NAMES))),
        zero_division=0,
    )
    per_class = {
        name: {
            "precision": float(precision[index]),
            "recall": float(recall[index]),
            "f1": float(f1[index]),
            "support": int(support[index]),
        }
        for index, name in enumerate(CLASS_NAMES)
    }
    auc_by_class: dict[str, float | None] = {}
    for index, name in enumerate(CLASS_NAMES):
        binary_labels = (labels == index).astype(int)
        try:
            auc_by_class[name] = float(roc_auc_score(binary_labels, probabilities[:, index]))
        except ValueError:
            auc_by_class[name] = None

    accepted_accuracy = (
        float(accuracy_score(labels[accepted], predictions[accepted])) if accepted.any() else None
    )
    return {
        "sample_count": int(len(labels)),
        "accuracy": float(accuracy_score(labels, predictions)),
        "balanced_accuracy": float(balanced_accuracy_score(labels, predictions)),
        "macro_f1": float(f1_score(labels, predictions, average="macro", zero_division=0)),
        "per_class": per_class,
        "per_class_roc_auc": auc_by_class,
        "confidence_threshold": float(threshold),
        "accepted_count": int(accepted.sum()),
        "coverage": float(accepted.mean()) if len(accepted) else 0.0,
        "accuracy_at_threshold": accepted_accuracy,
        "ece": expected_calibration_error(probabilities, labels),
        "classification_report": classification_report(
            labels,
            predictions,
            labels=list(range(len(CLASS_NAMES))),
            target_names=list(CLASS_NAMES),
            output_dict=True,
            zero_division=0,
        ),
    }


def save_evaluation_plots(
    labels: np.ndarray,
    probabilities: np.ndarray,
    output_dir: Path,
    suffix: str,
    before_calibration: np.ndarray | None = None,
) -> None:
    output_dir.mkdir(parents=True, exist_ok=True)
    matrix = confusion_matrix(labels, probabilities.argmax(axis=1), labels=list(range(len(CLASS_NAMES))))
    figure, axis = plt.subplots(figsize=(7, 6))
    sns.heatmap(matrix, annot=True, fmt="d", cmap="crest", xticklabels=CLASS_NAMES, yticklabels=CLASS_NAMES, ax=axis)
    axis.set_xlabel("Predicted class")
    axis.set_ylabel("True class")
    axis.set_title("Patient-grouped held-out confusion matrix")
    figure.tight_layout()
    figure.savefig(output_dir / f"confusion-matrix-{suffix}.png", dpi=160)
    plt.close(figure)

    figure, axis = plt.subplots(figsize=(6, 5))
    axis.plot([0, 1], [0, 1], linestyle="--", color="#777777", label="Ideal")
    for probs, label in [
        *(([(before_calibration, "Before temperature scaling")] if before_calibration is not None else [])),
        (probabilities, "After temperature scaling"),
    ]:
        confidence = probs.max(axis=1)
        correctness = (probs.argmax(axis=1) == labels).astype(float)
        edges = np.linspace(0, 1, 11)
        bin_confidence, bin_accuracy = [], []
        for low, high in zip(edges[:-1], edges[1:]):
            mask = (confidence > low) & (confidence <= high)
            if mask.any():
                bin_confidence.append(float(confidence[mask].mean()))
                bin_accuracy.append(float(correctness[mask].mean()))
        axis.plot(bin_confidence, bin_accuracy, marker="o", label=label)
    axis.set(xlim=(0, 1), ylim=(0, 1), xlabel="Mean confidence", ylabel="Observed accuracy")
    axis.set_title("Reliability diagram")
    axis.legend()
    figure.tight_layout()
    figure.savefig(output_dir / f"reliability-{suffix}.png", dpi=160)
    plt.close(figure)


def save_metrics(metrics: dict, path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(metrics, indent=2, allow_nan=False) + "\n", encoding="utf-8")


def main() -> None:
    import argparse

    parser = argparse.ArgumentParser(description="Print metrics generated by a completed training run.")
    parser.add_argument("--metrics", default="outputs/metrics-fusion.json")
    args = parser.parse_args()
    path = Path(args.metrics)
    if not path.exists():
        raise SystemExit(f"No metrics file found at {path}. Train on PAD-UFES-20 first.")
    print(path.read_text(encoding="utf-8"))


if __name__ == "__main__":
    main()
